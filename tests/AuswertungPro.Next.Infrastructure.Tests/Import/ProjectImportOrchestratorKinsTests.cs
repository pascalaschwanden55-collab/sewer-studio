    [Fact]
    public void Import_Kins_XtfMassgeblich_MitAllenAnreicherungenUndVerteilung()
    {
        var (sourceDir, projectDir) = ErstelleMiniKinsFixture();
        var project = new Project();

        var result = ErzeugeOrchestrator().Import(sourceDir, projectDir, project);

        Assert.Equal(KanalExportFormat.Kins, result.Format);

        // Haltung: Name aus Schachtpaar, Laenge aus Rohrende, Strasse aus DBF
        var record = Assert.Single(project.Data);
        Assert.Equal("58951-58950", record.GetFieldValue("Haltungsname"));
        Assert.Equal("30.4", record.GetFieldValue("Haltungslaenge_m"));
        Assert.Equal("Grünweg", record.GetFieldValue("Strasse"));

        // Timecode aus kiDVDaten.txt am BBBA-Eintrag
        var bbba = record.Protocol!.Current.Entries.Single(e => e.Code == "BBBA");
        Assert.Equal("0:06:07", bbba.Mpeg);

        // Schaechte aus schacht.DBF
        Assert.Equal(2, project.SchaechteData.Count);

        // Video verteilt + relativ verlinkt
        var link = record.GetFieldValue("Link");
        Assert.False(Path.IsPathRooted(link), $"Link nicht relativ: {link}");
        Assert.True(File.Exists(Path.Combine(projectDir, link!)), $"Video fehlt: {link}");

        // DP-Kandidaten aus dem DP_Gross-Ordner wurden angefasst (Fake-PDFs sind
        // inhaltlich nicht zuordenbar → als nicht zugeordnet gemeldet, kein Absturz).
        Assert.Contains(result.Messages, m => m.StartsWith("Dichtheitspruefung:", StringComparison.Ordinal));

        // XTF archiviert
        Assert.True(
            Directory.EnumerateFiles(projectDir, "*.XTF", SearchOption.AllDirectories).Any(),
            "XTF nicht archiviert");
    }

