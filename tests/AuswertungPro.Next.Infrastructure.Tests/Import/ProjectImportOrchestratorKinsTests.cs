        Directory.CreateDirectory(Path.Combine(projectDir, "Haltungen_Verteilt", "10081-8993"));

        var pruefprotokoll = Path.Combine(dokumente, "260622131802.pdf");
        WritePdf(
            pruefprotokoll,
