    [Fact]
    public void Import_Kins_ZweiterLauf_IstIdempotent()
    {
        var (sourceDir, projectDir) = ErstelleMiniKinsFixture();
        var project = new Project();
        var orch = ErzeugeOrchestrator();

        orch.Import(sourceDir, projectDir, project);
        orch.Import(sourceDir, projectDir, project);

        Assert.Single(project.Data); // kein "10"-Duplikat
        Assert.Equal(2, project.SchaechteData.Count);

        var haltungsOrdner = Path.Combine(projectDir, "Haltungen_Verteilt", "58951-58950");
        var duplikate = Directory.EnumerateFiles(haltungsOrdner)
            .Where(f => Path.GetFileNameWithoutExtension(f).EndsWith("_1", StringComparison.Ordinal))
            .ToList();
        Assert.Empty(duplikate);
    }

