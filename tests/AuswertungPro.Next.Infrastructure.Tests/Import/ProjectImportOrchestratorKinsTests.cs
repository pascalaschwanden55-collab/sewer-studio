            "10081-8993",
            "20260622_10081-8993_DP.pdf")));
    }

    [Fact]
    public void DichtheitVerteilung_UeberspringtBereitsVorhandene()
    {
        // Idempotenz-Guard: liegt im Ziel schon eine *_DP*.pdf gleicher Groesse,
        // wird der Kandidat nicht erneut verteilt (keine _01-Duplikate).
        var (sourceDir, projectDir) = ErstelleMiniKinsFixture();
        var quelle = Path.Combine(sourceDir, "048473_DP_Gross", "048473-Haltung10.pdf");
        var zielDir = Path.Combine(projectDir, "Haltungen_Verteilt", "58951-58950");
        Directory.CreateDirectory(zielDir);
        File.Copy(quelle, Path.Combine(zielDir, "20260622_58951-58950_DP.pdf"));

        var result = DichtheitImportDistributor.Distribute(new Project(), projectDir, sourceDir);

        Assert.Equal(1, result.Uebersprungen);
    }

    [Fact]
    public void Import_Kins_RenameBenenntVerteilteDateienMit()
    {
        // Nachweis: Die KINS-Verteilung nutzt exakt das Schema von "Haltung Verteilen" —
        // damit greift die bestehende Rename-Logik ohne Aenderung.
        var (sourceDir, projectDir) = ErstelleMiniKinsFixture();
        var project = new Project();
        ErzeugeOrchestrator().Import(sourceDir, projectDir, project);
        var record = Assert.Single(project.Data);

        var rename = AuswertungPro.Next.Application.Common.HoldingRenameService.Rename(
            record, "58951-58950", "99999-88888",
            Path.Combine(projectDir, "projekt.json"));
        Assert.True(rename.Success, rename.ErrorMessage);
        record.SetFieldValue("Haltungsname", "99999-88888", FieldSource.Manual, userEdited: true);

        Assert.True(Directory.Exists(Path.Combine(projectDir, "Haltungen_Verteilt", "99999-88888")));
        Assert.False(Directory.Exists(Path.Combine(projectDir, "Haltungen_Verteilt", "58951-58950")));

        var link = record.GetFieldValue("Link");
        Assert.True(File.Exists(Path.Combine(projectDir, link!)), $"Video nach Rename nicht auffindbar: {link}");
    }

